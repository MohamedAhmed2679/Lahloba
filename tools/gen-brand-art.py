"""Generates packages/ui/src/brand/art.ts from the brand kit SVGs (drawn artwork, no fonts).
Usage: python3 tools/gen-brand-art.py <branding-dir>
Colours are mapped to semantic roles so components can recolour for dark mode/role accents:
  #2A1C17 -> ink, #8E2443 -> accent, #F7F0E3 -> paper, #E9A23B -> portion-on-dark.
"""
import json, re, sys, xml.etree.ElementTree as ET
root = sys.argv[1]
ROLE = {'#2A1C17': 'ink', '#8E2443': 'accent', '#F7F0E3': 'paper', '#E9A23B': 'turmeric'}
FILES = {
  'symbol': '02_Logo/recommended/lahloba_symbol_fullcolour.svg',
  'lockupEn': '02_Logo/recommended/lahloba_lockup_horizontal_en.svg',
  'lockupAr': '02_Logo/recommended/lahloba_lockup_horizontal_ar.svg',
  'appIcon': '02_Logo/recommended/lahloba_app_icon_1024.svg',
  'EAT_NOW': '05_Icons_Illustrations/icons/service_eat_now.svg',
  'HEAT_AT_HOME': '05_Icons_Illustrations/icons/service_heat_at_home.svg',
  'COOK_AT_HOME': '05_Icons_Illustrations/icons/service_cook_at_home.svg',
  'GROCERIES': '05_Icons_Illustrations/icons/service_groceries.svg',
  'LEARN': '05_Icons_Illustrations/icons/service_recipes_guidance.svg',
  'CHEF': '05_Icons_Illustrations/icons/role_chef.svg',
  'CUSTOMER': '05_Icons_Illustrations/icons/role_customer.svg',
  'COURIER': '05_Icons_Illustrations/icons/role_delivery.svg',
  'SUPPLIER': '05_Icons_Illustrations/icons/role_supplier.svg',
}
NS = '{http://www.w3.org/2000/svg}'
ATTRS = {'d':'d','transform':'transform','stroke-width':'strokeWidth','stroke-linecap':'strokeLinecap','stroke-linejoin':'strokeLinejoin',
         'cx':'cx','cy':'cy','r':'r','x':'x','y':'y','width':'width','height':'height','rx':'rx'}
def node(el):
    tag = el.tag.replace(NS, '')
    if tag in ('title', 'metadata') or '}' in el.tag and NS not in el.tag: return None
    out = {'t': tag}
    for k, v in el.attrib.items():
        if k in ('fill', 'stroke'):
            out[k] = 'none' if v == 'none' else ROLE.get(v.upper(), v)
        elif k in ATTRS:
            out[ATTRS[k]] = float(v) if re.fullmatch(r'-?[\d.]+', v) else v
    kids = [n for n in (node(c) for c in el) if n]
    if kids: out['c'] = kids
    return out
art = {}
for key, rel in FILES.items():
    txt = open(f'{root}/{rel}', encoding='utf8').read()
    txt = re.sub(r'<metadata>.*?</metadata>', '', txt, flags=re.S)
    svg = ET.fromstring(txt)
    art[key] = {'viewBox': svg.attrib['viewBox'], 'c': [n for n in (node(c) for c in svg) if n]}
print('// GENERATED by tools/gen-brand-art.py from the Lahloba brand kit (PROPOSAL, not approved). Do not edit by hand.')
print('export type ArtNode = { t: string; c?: ArtNode[]; fill?: string; stroke?: string; [k: string]: unknown };')
print('export const ART: Record<string, { viewBox: string; c: ArtNode[] }> = ' + json.dumps(art, ensure_ascii=False, indent=1) + ';')
